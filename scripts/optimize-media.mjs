import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {media} from '../src/content/media.ts';
import {websitePortfolioDefaults} from '../src/features/cms/website-portfolio.ts';
import {advertisingPortfolioDefaults} from '../src/features/cms/advertising-portfolio.ts';

const root=process.cwd(),publicRoot=path.join(root,'public');
const ffmpeg=process.env.FFMPEG||path.join(root,'.tools/video/imageio_ffmpeg/binaries/ffmpeg-win-x86_64-v7.1.exe');
if(!fs.existsSync(ffmpeg))throw Error('Set FFMPEG to an installed FFmpeg executable.');
const work=path.join(root,'.tools/media-delivery');fs.mkdirSync(work,{recursive:true});
for(const dir of ['media','posters'])fs.mkdirSync(path.join(publicRoot,'optimized',dir),{recursive:true});
const manifestFile=path.join(root,'src/content/media-delivery.ts');
const reportFile=path.join(work,'report.json');
const previous=fs.existsSync(reportFile)?JSON.parse(fs.readFileSync(reportFile,'utf8')):null;
const inputs=[...Object.values(media).map(m=>({id:m.id,src:m.src,kind:'world'})),
 ...websitePortfolioDefaults.items.map(m=>({id:'website-'+m.slug,src:m.video,kind:'preview',poster:m.poster})),
 ...advertisingPortfolioDefaults.items.map(m=>({id:'film-'+m.slug,src:m.video,kind:'film',poster:m.poster}))];
const digest=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const run=args=>{const result=spawnSync(ffmpeg,['-nostdin','-hide_banner','-loglevel','error','-y',...args],{encoding:'utf8',windowsHide:true,maxBuffer:4*1024*1024});if(result.status!==0)throw Error(result.stderr||'FFmpeg failed');};
const sources={},report=[];
for(const input of inputs){
 if(sources[input.src])continue;
 const original=path.resolve(publicRoot,decodeURIComponent(input.src).replace(/^\//,''));
 if(!original.startsWith(publicRoot+path.sep))throw Error('Unsafe source path');
 const sourceHash=digest(original),sourceBytes=fs.statSync(original).size;
 const old=previous?.items?.find(x=>x.source===input.src&&x.sourceHash===sourceHash&&x.recipe==='v1');
 if(old&&Object.values(old.variants).every(v=>fs.existsSync(path.join(publicRoot,v.url)))){
  sources[input.src]={desktop:old.variants.desktop.url,mobile:old.variants.mobile.url,poster:old.poster};
  report.push(old);console.log('Reused '+input.id);continue;
 }
 const variants={};
 for(const variant of ['desktop','mobile']){
  const small=variant==='mobile',width=input.kind==='film'?(small?540:720):input.kind==='preview'?(small?640:960):(small?854:1280);
  const temporary=path.join(work,input.id+'-'+variant+'.mp4');
  const args=['-i',original,'-map','0:v:0','-vf','scale=min('+width+'\\,iw):-2','-c:v','libx264','-preset','medium','-crf',String(input.kind==='film'?(small?24:23):(small?26:24)),'-threads','2','-pix_fmt','yuv420p','-map_metadata','-1'];
  if(input.kind==='film')args.push('-map','0:a:0?','-c:a','aac','-b:a','128k');else args.push('-an');
  args.push('-movflags','+faststart',temporary);run(args);
  const bytes=fs.statSync(temporary).size,hash=digest(temporary);
  // Never replace a smaller owner asset with a larger derivative.
  if(bytes>=sourceBytes){variants[variant]={url:input.src,bytes:sourceBytes,sha256:sourceHash,width};continue;}
  const url='/optimized/media/'+input.id+'-'+variant+'.'+hash.slice(0,12)+'.mp4';
  fs.copyFileSync(temporary,path.join(publicRoot,url));variants[variant]={url,bytes,sha256:hash,width};
 }
 let poster=input.poster;
 if(!poster){
  const temporary=path.join(work,input.id+'.webp');
  run(['-ss','0.5','-i',original,'-frames:v','1','-vf','scale=min(960\\,iw):-2','-c:v','libwebp','-quality','78',temporary]);
  poster='/optimized/posters/'+input.id+'.'+digest(temporary).slice(0,12)+'.webp';
  fs.copyFileSync(temporary,path.join(publicRoot,poster));
 }
 sources[input.src]={desktop:variants.desktop.url,mobile:variants.mobile.url,poster};
 report.push({source:input.src,sourceHash,sourceBytes,kind:input.kind,recipe:'v1',poster,variants});
 console.log(JSON.stringify({id:input.id,original:sourceBytes,desktop:variants.desktop.bytes,mobile:variants.mobile.bytes}));
}
const totals=report.reduce((a,x)=>({original:a.original+x.sourceBytes,desktop:a.desktop+x.variants.desktop.bytes,mobile:a.mobile+x.variants.mobile.bytes}),{original:0,desktop:0,mobile:0});
fs.writeFileSync(manifestFile,'// Generated by npm run optimize:media. Originals remain unchanged.\nexport const mediaDelivery: Record<string,{desktop:string;mobile:string;poster:string}> = '+JSON.stringify(sources,null,2)+';\n');
fs.writeFileSync(reportFile,JSON.stringify({totals,items:report},null,2));
console.log(JSON.stringify({totals,reduction:{desktop:1-totals.desktop/totals.original,mobile:1-totals.mobile/totals.original}}));
